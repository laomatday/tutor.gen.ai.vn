import { readFile, writeFile } from "node:fs/promises";

const sources = [
  new URL("../src/index.css", import.meta.url),
  new URL("../src/styles/tutor-compat.css", import.meta.url),
];
const destination = new URL("../design-tokens.json", import.meta.url);
const css = (await Promise.all(sources.map(source => readFile(source, "utf8")))).join("\n");
const tokens = Object.fromEntries(
  [...css.matchAll(/^\s*(--[\w-]+):\s*([^;]+);/gm)].map(([, name, value]) => [
    name,
    value.trim(),
  ]),
);
if (!Object.keys(tokens).length) throw new Error("No CSS design tokens found.");
await writeFile(
  destination,
  `${JSON.stringify(
    {
      $description:
        "Generated from the genAi core plus inline Tutor compatibility aliases and runtime compatibility components. Do not edit this file by hand.",
      source: ["src/index.css", "src/styles/tutor-compat.css"],
      tokens,
    },
    null,
    2,
  )}\n`,
);
console.log(`Exported ${Object.keys(tokens).length} design tokens.`);
