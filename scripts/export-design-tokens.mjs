import { readFile, writeFile } from "node:fs/promises";

const source = new URL("../src/styles/tokens.css", import.meta.url);
const destination = new URL("../design-tokens.json", import.meta.url);
const css = await readFile(source, "utf8");
const tokens = Object.fromEntries(
  [...css.matchAll(/^\s*(--[\w-]+):\s*([^;]+);/gm)].map(([, name, value]) => [
    name,
    value.trim(),
  ]),
);
if (!Object.keys(tokens).length) throw new Error("No CSS design tokens found.");
await writeFile(
  destination,
  `${JSON.stringify(
    {
      $description:
        "Generated from src/styles/tokens.css. Run the export script after editing the CSS source; do not edit this file by hand.",
      source: "src/styles/tokens.css",
      tokens,
    },
    null,
    2,
  )}\n`,
);
console.log(`Exported ${Object.keys(tokens).length} design tokens.`);
